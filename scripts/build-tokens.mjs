// Generates every file derived from app/styles/tokens.ts (DESIGN §2.1):
// the CSS custom properties with the Tailwind theme over them
// (scripts/tailwind-theme.mjs), the favicon, the web manifest and the
// theme-color values. `npm run gen:tokens` writes them; `npm run check:tokens`
// (in validate) fails if any of them differs from what would be written now.
// Run through tsx, which loads the TypeScript token module.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import {
  channelString,
  COLOURS,
  DURATIONS,
  EASINGS,
  LAYOUT,
  MD_BREAKPOINT,
  resolveColour,
  THEME_EFFECTS,
  TYPE_SCALE,
} from "../app/styles/tokens.ts";
import { LOGO_MARK_PATHS } from "../app/components/logo-mark-paths.ts";
import { runtimeVariable, tailwindThemeCss } from "./tailwind-theme.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const NOTICE =
  "@generated by scripts/build-tokens.mjs from app/styles/tokens.ts. Do not edit; run `npm run gen:tokens`.";

function colourDeclarations(theme) {
  const colours = Object.entries(COLOURS[theme]).map(([name, value]) =>
    typeof value === "string"
      ? `${runtimeVariable(name)}: ${channelString(value)}; /* ${value} */`
      : `${runtimeVariable(name)}: var(${runtimeVariable(value.alias)});`
  );
  const effects = Object.entries(THEME_EFFECTS[theme]).map(
    ([name, value]) => `${runtimeVariable(name)}: ${value};`
  );
  return [`color-scheme: ${theme};`, ...colours, ...effects].join("\n");
}

function responsiveDeclarations(pick) {
  const entries = [
    ...Object.entries(TYPE_SCALE).map(([name, style]) => [
      `text-${name}`,
      style.size,
    ]),
    ...Object.entries(LAYOUT),
  ];
  return entries
    .flatMap(([name, sizes]) => {
      const value = pick(sizes);
      return value === undefined ? [] : [`${runtimeVariable(name)}: ${value};`];
    })
    .join("\n");
}

/**
 * The per-theme and responsive variables (`--bt-*`, read at run time), then
 * the Tailwind `@theme` over them and the named utilities.
 */
async function tokensCss() {
  const motion = [
    ...Object.entries(DURATIONS).map(
      ([name, value]) => `${runtimeVariable(`dur-${name}`)}: ${value};`
    ),
    ...Object.entries(EASINGS).map(
      ([name, value]) => `${runtimeVariable(`ease-${name}`)}: ${value};`
    ),
  ].join("\n");
  return `/* ${NOTICE} */
:root, [data-theme="light"] {
${colourDeclarations("light")}
}
:root[data-theme="dark"], [data-theme="dark"] {
${colourDeclarations("dark")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colourDeclarations("dark")}
  }
}
:root {
${responsiveDeclarations(sizes => sizes[0])}
${motion}
}
@media (min-width: ${MD_BREAKPOINT}) {
  :root {
${responsiveDeclarations(sizes => sizes[1])}
  }
}
${await tailwindThemeCss()}`;
}

function faviconSvg() {
  const fill = theme =>
    [
      `.handle { fill: ${resolveColour(theme, "fg")}; }`,
      `.flame { fill: ${resolveColour(theme, "accent")}; }`,
      `.core { fill: ${resolveColour(theme, "logo-core")}; }`,
    ].join(" ");
  const rects = LOGO_MARK_PATHS.cresset
    .map(
      ({ x, y, width, height, rx }) =>
        `  <rect class="handle" x="${x}" y="${y}" width="${width}" height="${height}" rx="${rx}"/>`
    )
    .join("\n");
  return `<!-- ${NOTICE} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">
  <style>${fill("light")} @media (prefers-color-scheme: dark) { ${fill("dark")} }</style>
  <path class="handle" d="${LOGO_MARK_PATHS.handle}"/>
${rects}
  <path class="flame" d="${LOGO_MARK_PATHS.flame}"/>
  <path class="core" d="${LOGO_MARK_PATHS.core}"/>
</svg>
`;
}

function webManifest() {
  const canvas = resolveColour("light", "canvas");
  return JSON.stringify({
    "//": NOTICE,
    name: "Bardic Torch",
    short_name: "Bardic Torch",
    start_url: "/",
    display: "browser",
    icons: [{ src: "/favicon.svg", type: "image/svg+xml", sizes: "any" }],
    theme_color: canvas,
    background_color: canvas,
  });
}

function themeColourModule() {
  return `// ${NOTICE}

/** \`<meta name="theme-color">\` per theme: the \`canvas\` token. */
export const THEME_COLOURS = {
  light: "${resolveColour("light", "canvas")}",
  dark: "${resolveColour("dark", "canvas")}",
} as const;
`;
}

async function formatted(path, source) {
  const file = `${ROOT}${path}`;
  const { inferredParser } = await prettier.getFileInfo(file);
  if (!inferredParser) return source;
  const config = await prettier.resolveConfig(file);
  return prettier.format(source, { ...config, filepath: file });
}

/**
 * Every generated file, as `{ path, content }` with repo-relative paths.
 * @returns {Promise<{ path: string, content: string }[]>}
 */
export async function renderTokenFiles() {
  /** @type {[string, string][]} */
  const sources = [
    ["app/styles/tokens.css", await tokensCss()],
    ["app/styles/theme-colour.gen.ts", themeColourModule()],
    ["public/favicon.svg", faviconSvg()],
    ["public/site.webmanifest", webManifest()],
  ];
  return Promise.all(
    sources.map(async ([path, source]) => ({
      path,
      content: await formatted(path, source),
    }))
  );
}

async function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const { path, content } of await renderTokenFiles()) {
    const current = await readFile(`${ROOT}${path}`, "utf8").catch(() => null);
    if (current === content) continue;
    if (check) stale.push(path);
    else await writeFile(`${ROOT}${path}`, content);
  }
  if (stale.length > 0) {
    console.error(
      `check:tokens: out of date: ${stale.join(", ")}. Run \`npm run gen:tokens\`.`
    );
    process.exit(1);
  }
  console.log(
    check
      ? "check:tokens: generated token files are up to date"
      : "gen:tokens: generated token files written"
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
