/**
 * Writes test/fixtures/wiki-categories.json from a dump of the original wiki
 * (`categories.json` from the dump tooling), for app/constants/navigation.test.ts.
 *
 *   node scripts/wiki-categories.mjs <path to categories.json>
 *
 * The repo is public and the dump also has categories named after bards, so
 * only titles that can't be people are kept: the top-level categories and
 * every category under the facets the navigation links to. Nothing else
 * from the dump (pages, members, descriptions) is written.
 */
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = "Top Level Categories";
const FACETS = [
  "Genres",
  "Moods",
  "Topics",
  "Cultures",
  "Languages",
  "Legendaria",
  "Source Category",
  "Conservation Status",
];
/** Main-namespace pages the navigation links to (not categories). */
const PAGES = ["Collections", "Main Page"];
const OUTPUT = new URL(
  "../test/fixtures/wiki-categories.json",
  import.meta.url
);

const [source] = process.argv.slice(2);
if (!source) {
  console.error("Usage: node scripts/wiki-categories.mjs <categories.json>");
  process.exit(1);
}

const { generated, categories } = JSON.parse(readFileSync(source, "utf8"));
const subcategories = name => categories[name]?.subcategories ?? [];

const kept = new Set([ROOT, ...subcategories(ROOT)]);
const pending = [...FACETS];
while (pending.length > 0) {
  const name = pending.pop();
  if (!categories[name]) throw new Error(`The dump has no category ${name}`);
  if (kept.has(name) && !FACETS.includes(name)) continue;
  kept.add(name);
  pending.push(...subcategories(name).filter(child => !kept.has(child)));
}

const fixture = {
  "//": "Generated by scripts/wiki-categories.mjs from a dump of bardictorch's original wiki. Titles only.",
  snapshot: generated,
  categories: [...kept].sort((a, b) => a.localeCompare(b, "en")),
  pages: PAGES,
};
writeFileSync(OUTPUT, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(
  `Wrote ${fixture.categories.length} category titles to ${OUTPUT.pathname}`
);
